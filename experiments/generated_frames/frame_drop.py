"""Frame-drop rule for generated frames inside a real clip (paper Sec. 5.2, Supp. F).

For a video of T frames with NRG-PD predictions and cameras:

  s_t    = mean predicted NRG angle of frame t (degrees, all pixels of the 480x848 map);
  N(t)   = the K = 6 frames nearest to t in camera pose, among frames u with |u - t| > 3; the pose distance
           is the rotation angle between the two cameras (degrees) + 10 * centre distance / scene extent,
           with scene extent = largest distance of a camera centre from the mean centre;
  r_t    = s_t - median_{u in N(t)} s_u;
  sigma_r = 1.4826 * median_t |r_t - median(r)|  (robust SD over all T frames);
  frame t is dropped (left out of the 3DGS fit) if t is droppable and r_t >= c * sigma_r, c = 0.5.

c = 0.5 was chosen on validation clips. Random control: the same number of frames drawn uniformly from
the droppable frames, numpy.random.default_rng(2026111680 + k) for draws k = 0, 1, 2.

In the paper the video is the 162-frame palindrome of a clip (forward 0..80 with frames 25..55
generated by Wan from the real frames 24 and 56, then the real frames 80..0). NRG-PD scores the two
81-frame halves separately and its angle maps are resized bilinearly to 480x848. Held-out views
(forward 12, 36, 40, 44 and their mirrored copies) are not trained on, and palindrome frames
0, 80, 81, 161 are never dropped; pass them with --held-out and --exclude.

A dropped frame enters RobustSplat through the same keep archive as the pixel masks
(experiments/masked_3dgs/README.md): clutter_<t:03d>.png all zeros for a dropped frame, all ones else.

Example:
    python -m experiments.generated_frames.frame_drop --predictions pred_fwd.npz pred_rev.npz \
        --cameras cameras.npz --held-out 12 36 40 44 117 121 125 149 --exclude 0 80 81 161 --out drop.json
"""
from __future__ import annotations

import argparse
import json

import cv2
import numpy as np

K_NEIGHBOURS = 6
MIN_INDEX_GAP = 4          # neighbours must satisfy |u - t| > 3
CENTRE_WEIGHT = 10.0
C_DEFAULT = 0.5
MAD_TO_SD = 1.4826
RANDOM_SEED = 2026111680
OUT_HW = (480, 848)


def load_scores(paths: list[str]) -> np.ndarray:
    """Per-frame mean predicted angle, frames of all files concatenated in order.

    Reads 'degree_480x848' (as stored for the paper) or 'angle_deg' from nrgpd.infer, which is first
    resized bilinearly to 480x848.
    """
    out = []
    for p in paths:
        with np.load(p, allow_pickle=False) as z:
            if "degree_480x848" in z.files:
                d = z["degree_480x848"].astype(np.float32)
            else:
                a = z["angle_deg"].astype(np.float32)
                d = np.stack([cv2.resize(f, OUT_HW[::-1], interpolation=cv2.INTER_LINEAR) for f in a])
        out.append(d.reshape(len(d), -1).mean(1))
    return np.concatenate(out)


def load_cameras(path: str) -> tuple[np.ndarray, np.ndarray]:
    """Camera-to-world rotations and centres from an npz with world-to-camera 'w2c' (T, 4, 4)."""
    with np.load(path, allow_pickle=False) as z:
        c2w = np.linalg.inv(z["w2c"])
    return c2w[:, :3, :3], c2w[:, :3, 3]


def relative_scores(scores: np.ndarray, rot: np.ndarray, centres: np.ndarray, k: int = K_NEIGHBOURS,
                    min_gap: int = MIN_INDEX_GAP) -> tuple[np.ndarray, dict[int, list[int]]]:
    """r_t = s_t - median of s over the k pose-nearest frames with |u - t| >= min_gap."""
    n = len(scores)
    ext = float(np.linalg.norm(centres - centres.mean(0), axis=1).max())
    rel = np.zeros(n)
    nbrs: dict[int, list[int]] = {}
    for t in range(n):
        cand = [s for s in range(n) if abs(s - t) >= min_gap]
        dist = []
        for s in cand:
            m = rot[t].T @ rot[s]
            ang = np.degrees(np.arccos(np.clip((np.trace(m) - 1) / 2, -1, 1)))
            dist.append(ang + CENTRE_WEIGHT * np.linalg.norm(centres[t] - centres[s]) / ext)
        nn = [cand[j] for j in np.argsort(dist)[:k]]
        nbrs[t] = nn
        rel[t] = scores[t] - np.median(scores[nn])
    return rel, nbrs


def drop_frames(rel: np.ndarray, droppable: list[int], c: float = C_DEFAULT) -> tuple[list[int], float]:
    """Droppable frames with r_t >= c * 1.4826 * MAD(r); returns (dropped, MAD)."""
    mad = float(np.median(np.abs(rel - np.median(rel))))
    return [i for i in droppable if rel[i] >= c * MAD_TO_SD * mad], mad


def random_control(droppable: list[int], n: int, draw: int, seed: int = RANDOM_SEED) -> list[int]:
    if not n:
        return []
    g = np.random.default_rng(seed + draw)
    return sorted(int(x) for x in g.choice(droppable, n, replace=False).tolist())


def write_keep_archive(train_frames: list[int], dropped: set[int], path: str, hw: tuple[int, int] = OUT_HW) -> None:
    np.savez_compressed(path, **{f"clutter_{i:03d}.png": (np.zeros(hw, np.uint8) if i in dropped else np.ones(hw, np.uint8))
                                 for i in train_frames})


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--predictions", nargs="+", required=True, help="NRG-PD .npz files, frames in video order")
    ap.add_argument("--cameras", required=True, help="npz with world-to-camera 'w2c' (T, 4, 4) of the fit")
    ap.add_argument("--c", type=float, default=C_DEFAULT)
    ap.add_argument("--exclude", type=int, nargs="*", default=[], help="trained frames that are never dropped")
    ap.add_argument("--held-out", type=int, nargs="*", default=None,
                    help="frames not trained on: never dropped and absent from the keep archive")
    ap.add_argument("--random-draws", type=int, default=3)
    ap.add_argument("--out", required=True, help="output JSON")
    ap.add_argument("--keep-out", default=None, help="RobustSplat keep archive for the rule's dropped frames")
    args = ap.parse_args()
    scores = load_scores(args.predictions)
    rot, centres = load_cameras(args.cameras)
    if len(rot) != len(scores):
        raise ValueError(f"{len(scores)} scored frames but {len(rot)} cameras")
    held = set(args.held_out or [])
    droppable = [i for i in range(len(scores)) if i not in set(args.exclude) and i not in held]
    rel, nbrs = relative_scores(scores, rot, centres)
    dropped, mad = drop_frames(rel, droppable, args.c)
    rand = {k: random_control(droppable, len(dropped), k) for k in range(args.random_draws)}
    if args.keep_out:
        write_keep_archive([i for i in range(len(scores)) if i not in held], set(dropped), args.keep_out)
    out = {"c": args.c, "k": K_NEIGHBOURS, "dropped": dropped, "random_dropped": rand,
           "random_seeds": [RANDOM_SEED + k for k in range(args.random_draws)], "mad": mad,
           "score": scores.tolist(), "rel": rel.tolist(), "neighbours": {str(t): v for t, v in nbrs.items()}}
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(json.dumps({"frames": len(scores), "droppable": len(droppable), "dropped": len(dropped)}))


if __name__ == "__main__":
    main()
